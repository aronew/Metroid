def card(id, group, kind, file, title, about, canvas, game, attach, task, rows,
         outline=LINE, pilot=False, note=""):
    return {"id": id, "group": group, "kind": kind, "file": file, "title": title,
            "about": about, "canvas": canvas, "game": game, "attach": attach,
            "task": task, "rows": rows, "outline": outline, "pilot": pilot,
            "note": note}


def hero_attach(*extra):
    """Every animation card attaches the approved model sheet and key poses,
    then image A, plus any sheet it continues from."""
    return ["H1", "H3"] + list(extra) + ["A"]


